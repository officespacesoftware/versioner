  /**
   * Step 9: Create GitHub Release
   */
  private async executeReleaseStep9_CreateGitHubRelease(
    branchInfo: BranchTypeInfo
  ): Promise<void> {
    this.updateStepStatus(9, "in_progress");

    try {
      console.log(`🔄 Step 9: Creating GitHub Release`);

      const context = this.context as ReleaseVersionWorkflowContext;
      const branchName = branchInfo.name.replace(/^remotes\/origin\//, "");

      // A dry run never promotes, so targetVersion is unset; derive what the release
      // would be named instead of treating its absence as a failure.
      if (context.dryRun) {
        const predicted = predictPromotedVersion(branchInfo.version.full);
        const step = this.updateStepStatus(9, "skipped");
        step.message = `Dry run: would create GitHub release ${predicted} targeting ${branchName}`;
        console.log(`⏭️  Step 9: skipped (dry run) — ${step.message}`);
        return;
      }

      if (!context.targetVersion) {
        throw new Error("Target version not available in context");
      }

      const version = context.targetVersion.version;

      const { url: releaseUrl, notesWarning } =
        await this.gitFlowManager.createGitHubRelease(version, branchName);

      context.releaseUrl = releaseUrl;
      if (notesWarning) {
        context.releaseNotesWarning = notesWarning;
        console.warn(`⚠️  Release notes warning: ${notesWarning}`);
      }

      console.log(`🎯 GitHub Release created: ${releaseUrl}`);
      console.log(`📋 Version: ${version}`);
      console.log(`🌿 Target branch: ${branchName}`);

      this.updateStepStatus(9, "completed");
    } catch (error) {
      this.updateStepStatus(9, "failed");
      throw error;
    }
  }

  /**
   * Step 10: Open or update the pull request on the branch's own base.
   *
   * A release branch integrates back into develop, and that PR is opened by
   * `create_release_candidate` and rewritten by every `increment_release_candidate`.
   * Promotion used to leave it alone, so it kept advertising the RC version and a
   * "use release_version when ready" next step that had just been carried out.
   *
   * Opens one when none is open, rather than only refreshing. By promotion time the
   * previous candidate's PR has usually been merged rather than left waiting, and the
   * point of the PR is to get the promotion and any fixes made on the RC into develop
   * straight away, keeping the release branch's divergence short.
   * Waiting for the release → develop downmerge, which does not run until after the
   * deploy, leaves them stranded on the release branch for as long as the deploy takes.
   *
   * Failure is recorded and reported, never fatal — the tag, the push and the GitHub
   * release have already happened by this point.
   */
  private async executeReleaseStep10_RefreshOwnBasePR(
    branchInfo: BranchTypeInfo
  ): Promise<void> {
    this.updateStepStatus(10, "in_progress");

    const context = this.context as ReleaseVersionWorkflowContext;
    const branchName = branchInfo.name.replace(/^remotes\/origin\//, "");
    const ownBase = this.integrationBase(branchInfo);
    context.ownBaseBranch = ownBase;

    // Whatever step 7 already wrote is not written again here: running both against
    // one head/base pair would leave that pull request's title decided by whichever
    // went last.
    if (ownBase === "main") {
      const step = this.updateStepStatus(10, "skipped");
      step.message = `${branchName} integrates into main, already handled in step 7`;
      console.log(`⏭️  Step 10: skipped — ${step.message}`);
      return;
    }

    if (context.dryRun) {
      const step = this.updateStepStatus(10, "skipped");
      step.message = `Dry run: would refresh an open ${branchName} → ${ownBase} PR`;
      console.log(`⏭️  Step 10: skipped (dry run) — ${step.message}`);
      return;
    }

    console.log(`🔄 Step 10: Opening or updating the ${branchName} → ${ownBase} PR`);

    try {
      const version =
        context.targetVersion?.version ||
        predictPromotedVersion(branchInfo.version.full);

      // createPullRequest opens one, or falls back to updating when GitHub reports one
      // is already open for this head and base. A hotfix's stays the draft
      // placeholder: it conflicts on VERSION until the downmerge reconciles it, so
      // it is never presented as ready to merge.
      const hotfix = branchInfo.type === "hotfix";
      const result = await this.gitFlowManager.createPullRequest(
        branchName,
        ownBase,
        // Deliberately the title the matching downmerge uses, so the two actions
        // converge on one wording instead of overwriting each other.
        `${hotfix ? "Hotfix" : "Release"} ${version} to ${ownBase}`,
        hotfix
          ? this.trackingPullRequestBody(branchName, version)
          : this.ownBasePullRequestBody(branchInfo, branchName, ownBase, version),
        hotfix
      );

      context.ownBasePullRequestUrl = result.url;
      context.ownBasePullRequestAction = result.action;
      const verb = result.action === "updated" ? "Updated" : "Opened";
      console.log(`   ✅ ${verb} PR: ${result.url}`);
      this.updateStepStatus(10, "completed");
    } catch (error) {
      const msg = error instanceof Error ? error.message : String(error);
      context.ownBasePullRequestError = msg;
      this.updateStepStatus(10, "completed");
      console.warn(`⚠️  Could not refresh the ${ownBase} PR: ${msg}`);
    }
  }

  private ownBasePullRequestBody(
    branchInfo: BranchTypeInfo,
    branchName: string,
    ownBase: string,
    version: string
  ): string {
    const kind = branchInfo.type === "release" ? "Release" : "Hotfix";
    return [
      `## ${kind} ${version} to ${ownBase}`,
      ``,
      `\`${branchName}\` has been promoted from a release candidate to \`${version}\`, ` +
        `and this PR merges it back into \`${ownBase}\`.`,
      ``,
      `### 📋 ${kind} Information`,
      `- **Version**: \`${version}\``,
      `- **Branch**: \`${branchName}\``,
      `- **Target**: \`${ownBase}\``,
      `- **Type**: final version (released from RC)`,
      ``,
      `### 🔄 Next Steps`,
      `1. Merge once ${version} has been deployed to production.`,
      ``,
      `---`,
      autoGeneratedFooter(),
    ].join("\n");
  }

  /**
   * Check if versioner is available
   */
  isVersionerAvailable(): boolean {
    return this.versionerAdapter.isVersionerAvailable();
  }

  /**
   * Cleanup and disconnect
   */
  async cleanup(): Promise<void> {
    await this.versionerAdapter.disconnect();
  }
