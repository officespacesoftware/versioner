/**
 * A downmerge's plan, and the open pull request from an earlier run of a
 * merge-branch route that already holds the source, when there is one: the
 * apply then opens nothing new. `supersedes` is the branch whose direct pull
 * request that one replaces, still to be closed if it is open.
 */
interface MergeBranchDownmergeInspection {
  plan: ChangePlan;
  existing?: { number: number; url: string; head: string; supersedes?: string };
}

/** The action name a downmerge plan carries, naming its route. */
function downmergeAction(route: DownmergeRoute): string {
  return `downmerge ${route.source} → ${route.target}`;
}
