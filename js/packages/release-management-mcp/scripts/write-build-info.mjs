#!/usr/bin/env node
// Writes src/build-info.ts before tsc runs, so health_check can say which build is
// answering. A published package is not a git checkout, so the value has to be
// baked in at build time rather than read at runtime.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));

function git(args) {
  return execFileSync("git", args, {
    cwd: packageRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  }).trim();
}

function resolveCommit() {
  // CI publishes from a detached checkout where GITHUB_SHA is the authority.
  if (process.env.GITHUB_SHA) {
    return process.env.GITHUB_SHA.slice(0, 11);
  }
  try {
    const sha = git(["rev-parse", "--short=11", "HEAD"]);
    // A dirty tree means the build does not correspond to any commit, which is
    // exactly what you need to know when a fix seems not to have taken effect.
    const dirty = git(["status", "--porcelain"]).length > 0;
    return dirty ? `${sha}-dirty` : sha;
  } catch {
    return "unknown";
  }
}

const contents = `// Generated by scripts/write-build-info.mjs at build time. Do not edit.

export const BUILD_COMMIT = ${JSON.stringify(resolveCommit())};
export const BUILD_TIME = ${JSON.stringify(new Date().toISOString())};
`;

writeFileSync(join(packageRoot, "src", "build-info.ts"), contents);
